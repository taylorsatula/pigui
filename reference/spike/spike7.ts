import { BACKGROUND_CONTEXT as ctx } from "@earendil-works/chord/context";
import { createModels } from "@earendil-works/pi-ai/models";
import { fauxAssistantMessage, fauxProvider, fauxToolCall, type FauxResponseFactory } from "@earendil-works/pi-ai/providers/faux";
import { obj, str } from "@earendil-works/pi-schema";
import { CompactionTask, createRegistry, defineExtension, defineTool, Harness, hook, MemoryStorage } from "@earendil-works/pi-durable";
const big = "x".repeat(3000);
const step = defineTool({ name: "step", description: "s", parameters: obj({ n: str() }), async execute(a) { return { output: [{ type: "text", text: `did ${a.n} ${big}` }] }; } });
let hookCalls = 0;
const Handoff = defineExtension({ name: "handoff", hooks: [hook(CompactionTask, { beforeCompact: async (c, api) => { hookCalls++; return { summary: `HANDOFF(replaced ${c.entries.length} entries, reason ${c.reason})` }; } })] });
let n = 0;
const scenario: FauxResponseFactory = (context) => {
  const last: any = context.messages[context.messages.length - 1];
  const sawHandoff = context.messages.some((m: any) => JSON.stringify(m.content).includes("HANDOFF("));
  if (last.role === "user" && !String(JSON.stringify(last.content)).includes("go")) return fauxAssistantMessage("summary-fallback");
  n++;
  if (n <= 8) return fauxAssistantMessage(fauxToolCall("step", { n: String(n) }), { stopReason: "toolUse" });
  return fauxAssistantMessage(`finished; saw handoff: ${sawHandoff}`);
};
const faux = fauxProvider({ models: [{ id: "small", contextWindow: 8000, maxTokens: 1000 }] });
const top = () => { while (faux.getPendingResponseCount() < 6) faux.appendResponses([wrapped]); };
const wrapped: FauxResponseFactory = (...a) => { top(); return scenario(...a); };
faux.setResponses(Array(6).fill(wrapped));
const models = createModels(); models.setProvider(faux.provider);
const registry = createRegistry(); registry.install(defineExtension({ name: "x", tools: [step] })); registry.install(Handoff);
const h = await Harness.open(new MemoryStorage(), { models, registry, settings: { compaction: { reserveTokens: 2000, keepRecentTokens: 1500, backgroundTokens: 0 } } }, ctx);
const c = await h.createConversation({ ownership: { kind: "ownerless" }, agent: { model: { provider: "faux", modelId: "small" } } }, ctx);
const s = await (await c.submit({ type: "input", content: "go" }, ctx)).wait(ctx);
const all = await c.entries({ order: "ascending" }, 200, undefined, ctx);
console.log("status:", s.status, "| hook calls:", hookCalls, "| kinds:", all.items.map((e) => e.kind.replace("pi.", "")).join(" "));
const lastA: any = all.items.filter((e) => e.kind === "pi.assistant").at(-1)?.model?.[0];
console.log("final answer:", lastA?.content?.[0]?.text);
const comp: any = all.items.find((e) => e.kind === "pi.compaction");
console.log("compaction entry text:", JSON.stringify(comp?.model?.[0]?.content).slice(0, 200));
await h.close(ctx);
